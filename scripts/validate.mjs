#!/usr/bin/env node
import { access, lstat, mkdtemp, readFile, readdir, realpath, rm, stat } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import os from 'node:os';
import path from 'node:path';
import process from 'node:process';
import { canonicalBytes } from './lib/canonical-json.mjs';
import {
  comparableGeneratedFile,
  recordsFromRuntimeBundles,
  resolveTranslationPath,
  validateInventory,
  validateManifestPaths,
  validateManifestTopology,
  validateProvenance,
  validateScope,
  validateTargetState
} from './lib/invariants.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const MAX_JSON_BYTES = 20 * 1024 * 1024;
const MAX_BUNDLE_BYTES = 4 * 1024 * 1024;

async function readJson(relative, limit = MAX_JSON_BYTES) {
  const absolute = path.join(ROOT, ...relative.split('/'));
  const metadata = await stat(absolute);
  if (!metadata.isFile() || metadata.size > limit) throw new Error(`[input-budget] ${relative}: expected bounded regular file, actual ${metadata.size}`);
  const bytes = await readFile(absolute);
  let value;
  try { value = JSON.parse(bytes.toString('utf8')); } catch { throw new Error(`[json-syntax] ${relative}: expected valid JSON, actual invalid JSON`); }
  return { bytes, value };
}

async function loadBundles(manifest, root = ROOT) {
  const bundles = new Map();
  const extensionRoot = path.join(root, 'extension');
  const declaration = validateManifestPaths(manifest, { extensionRoot });
  const realExtensionRoot = await realpath(extensionRoot);
  for (const translation of declaration.translations) {
    const absolute = resolveTranslationPath(extensionRoot, translation.path);
    const relative = path.relative(extensionRoot, absolute);
    let current = extensionRoot;
    for (const segment of relative.split(path.sep)) {
      current = path.join(current, segment);
      const component = await lstat(current);
      if (component.isSymbolicLink()) throw new Error(`[manifest-path] ${translation.path}: expected path without symbolic links, actual linked component`);
    }
    const metadata = await lstat(absolute);
    if (!metadata.isFile() || metadata.size < 0 || metadata.size > MAX_BUNDLE_BYTES) throw new Error(`[input-budget] ${translation.path}: expected bounded regular file, actual ${metadata.size}`);
    const realFile = await realpath(absolute);
    const realRelative = path.relative(realExtensionRoot, realFile);
    if (!realRelative || realRelative.startsWith('..') || path.isAbsolute(realRelative)) throw new Error(`[manifest-path] ${translation.path}: expected file beneath extension root, actual escaped path`);
    const bytes = await readFile(absolute);
    let value;
    try { value = JSON.parse(bytes.toString('utf8')); } catch { throw new Error(`[json-syntax] ${translation.path}: expected valid JSON, actual invalid JSON`); }
    bundles.set(translation.path, value);
  }
  return bundles;
}

async function validateReproducibility(committed, provenance) {
  const cache = path.join(ROOT, `.cache/vscode-source-${provenance.source.tag}`);
  try { await access(cache); } catch {
    process.stdout.write(`Skipped upstream regeneration: ${path.relative(ROOT, cache)} is not present.\n`);
    return;
  }
  const temporary = await mkdtemp(path.join(os.tmpdir(), 'vscode-yue-validate-'));
  try {
    const result = spawnSync(process.execPath, [path.join(ROOT, 'scripts/source-generate.mjs'), '--cache', cache, '--output', temporary, '--inventory-only', '--check-reproducible'], {
      cwd: ROOT,
      encoding: 'utf8',
      maxBuffer: 4 * 1024 * 1024
    });
    if (result.error || result.status !== 0) throw new Error(`[reproducibility] source generation: expected successful disposable generation, actual failed (${String(result.stderr || result.error?.message || '').trim()})`);
    const relatives = ['sources/inventory.en.json'];
    for (const relative of relatives) {
      const generated = JSON.parse(await readFile(path.join(temporary, ...relative.split('/')), 'utf8'));
      const expected = comparableGeneratedFile(relative, generated);
      const actualValue = committed.get(relative) ?? JSON.parse(await readFile(path.join(ROOT, ...relative.split('/')), 'utf8'));
      const actual = comparableGeneratedFile(relative, actualValue);
      if (!expected.equals(actual)) throw new Error(`[reproducibility] ${relative}: expected ${expected.length} canonical generated bytes, actual ${actual.length} canonical committed bytes`);
    }
  } finally {
    await rm(temporary, { recursive: true, force: true });
  }
}

async function main() {
  const inventoryFile = await readJson('sources/inventory.en.json');
  const provenanceFile = await readJson('sources/provenance.json', 2 * 1024 * 1024);
  const scopeFile = await readJson('sources/scope.json', 2 * 1024 * 1024);
  const manifestFile = await readJson('extension/package.json', 2 * 1024 * 1024);

  validateProvenance(provenanceFile.value, inventoryFile.value, canonicalBytes(inventoryFile.value), scopeFile.value);
  validateInventory(inventoryFile.value, inventoryFile.bytes);
  validateScope(inventoryFile.value, scopeFile.value);
  const bundles = await loadBundles(manifestFile.value);
  validateManifestTopology(inventoryFile.value, manifestFile.value, bundles, { extensionRoot: path.join(ROOT, 'extension') });
  const targets = recordsFromRuntimeBundles(inventoryFile.value, manifestFile.value, bundles);
  validateTargetState(inventoryFile.value, targets);
  const committed = new Map([
    ['sources/inventory.en.json', inventoryFile.value],
    ['sources/provenance.json', provenanceFile.value],
    ['sources/scope.json', scopeFile.value],
    ['extension/package.json', manifestFile.value]
  ]);
  await validateReproducibility(committed, provenanceFile.value);
  for (const script of ['release-generate.mjs', 'release-validate.mjs']) {
    const args = script === 'release-generate.mjs' ? ['--check'] : ['--candidate'];
    const result = spawnSync(process.execPath, [path.join(ROOT, 'scripts', script), ...args], { cwd: ROOT, encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 });
    if (result.error || result.status !== 0) throw new Error(`[release-validation] ${script}: ${String(result.stderr || result.error?.message || '').trim()}`);
  }
  process.stdout.write(`Validated ${inventoryFile.value.units.length} English units, ${manifestFile.value.contributes.localizations[0].translations.length} runtime bundles, protected syntax, and reproducible canonical outputs.\n`);
}

main().catch(error => {
  process.stderr.write(`${error instanceof Error ? error.message : String(error)}\n`);
  process.exitCode = 1;
});
